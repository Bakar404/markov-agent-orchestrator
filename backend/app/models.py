"""SQLAlchemy ORM models.

Every column type used here exists in both SQLite and PostgreSQL so the schema migrates
without change. JSON payloads carry the parts of the model that evolve fastest (state
snapshots, reward breakdowns, policy parameters).
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    JSON,
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def new_id() -> str:
    return uuid.uuid4().hex


class Base(DeclarativeBase):
    pass


class Run(Base):
    """A single orchestration episode."""

    __tablename__ = "runs"

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    task: Mapped[str] = mapped_column(Text, nullable=False)
    policy: Mapped[str] = mapped_column(String(64), nullable=False, default="contextual_bandit")
    status: Mapped[str] = mapped_column(String(24), nullable=False, default="created")
    seed: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    step_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    cumulative_reward: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    total_cost: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    total_latency_ms: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    total_tokens: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    terminated: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    termination_reason: Mapped[str | None] = mapped_column(String(128), nullable=True)
    config: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    current_state: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    initial_state: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    policy_state: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow
    )

    states: Mapped[list["StateSnapshot"]] = relationship(
        back_populates="run", cascade="all, delete-orphan", order_by="StateSnapshot.step"
    )
    traces: Mapped[list["Trace"]] = relationship(
        back_populates="run", cascade="all, delete-orphan", order_by="Trace.step"
    )
    messages: Mapped[list["Message"]] = relationship(
        back_populates="run", cascade="all, delete-orphan", order_by="Message.step"
    )


class StateSnapshot(Base):
    """Immutable snapshot of the orchestrator state after a step."""

    __tablename__ = "states"
    __table_args__ = (
        UniqueConstraint("run_id", "step", name="uq_state_run_step"),
        Index("ix_states_run", "run_id"),
    )

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    run_id: Mapped[str] = mapped_column(
        String(32), ForeignKey("runs.id", ondelete="CASCADE"), nullable=False
    )
    step: Mapped[int] = mapped_column(Integer, nullable=False)
    entropy: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    confidence: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    payload: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)

    run: Mapped[Run] = relationship(back_populates="states")


