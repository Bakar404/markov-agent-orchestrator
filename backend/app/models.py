    confidence: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    entropy_before: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    entropy_after: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
